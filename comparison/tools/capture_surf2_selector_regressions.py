"""Capture original x86 Amazing Surf 2 fold-mask boundaries, never C++ expectations.

Both implementations share prepared parameters; this does not independently
certify loader expansion or complete orbits. The original M3F CODE is immutable.
"""
import argparse
import json
import math
import os
from pathlib import Path
import struct

from capture_formula_regressions import literal
from check_formula_scene_points import execute, sha
from external_validation import ROOT, decode, slots, write_json


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for key in ('cpp', 'oracle', 'base', 'output', 'header'):
        parser.add_argument('--' + key, type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    asset = ROOT / 'mb3d/M3Formulas/Amazing Surf 2.m3f'
    code = args.output / 'original-code.bin'
    code.write_bytes(bytes.fromhex(asset.read_text().split('[CODE]')[1].split('[END]')[0]))
    data = decode(args.base)
    slot = next(s for s in slots(data) if s['name'] == 'Amazing Surf 2')
    offset = 848 + 188 * slot['slot']
    struct.pack_into('<i', data, offset + 8, 7)
    data[offset + 44:offset + 60] = bytes([0, 7, 0, 6, 6, 6, 2]).ljust(16, b'\0')
    values = [0., -0., 5e-324, -5e-324, 1e-310, -1e-310, 2.2250738585072014e-308,
              -2.2250738585072014e-308, 1e308, -1e308, math.inf, -math.inf, math.nan]
    # Scaled smooth cancellation at +/-1.5 and range bounds +/-2, FoldXY=.5.
    for v in (-4., -3., -2., -1., 1., 2., 3., 4.):
        values += [math.nextafter(v, -math.inf), v, math.nextafter(v, math.inf)]
    inputs = [[v, .25, -.5, .375] for v in values]
    inputs += [[.125, v, .5, 3.] for v in values]
    inputs += [[x, y, .25, .375] for x in (0., -0.) for y in (0., -0.)]
    stdin = ''.join(' '.join(format(v, '.17g') for v in xyz + [.2, -.3, .4, 1., -2., .375, 3.])
                    + '\n' for xyz in inputs)
    os.environ['MB3D_POINT_DERIVATIVES'] = '1'
    rows, cases, parameter_checks = [], [], []
    for mode in range(16):
        options = [2., .5, .5, 0., 0., 0., float(mode)] + [0.] * 9
        scene = bytearray(data)
        struct.pack_into('<16d', scene, offset + 60, *options)
        case_id = f'surf2_full_count_fold_{mode:02d}'
        path = args.output / (case_id + '.m3p')
        path.write_bytes(scene)
        blob = args.output / (case_id + '.params')
        # Dump only: the executable under repair contributes no expected value.
        execute([args.cpp.resolve(), 'Amazing Surf 2', path.resolve(), blob.resolve(), '--dump-only'], '')
        actual_mode = struct.unpack_from('<i', blob.read_bytes(), 512 - 0x50)[0]
        if actual_mode != mode:
            raise ValueError('Loader did not preserve the selected mask')
        parameter_checks.append(dict(case=case_id, requested=mode, prepared_int32=actual_mode,
                                     parameter_sha256=sha(blob)))
        expected = execute([args.oracle.resolve(), code.resolve(), blob.resolve()], stdin)
        if len(expected) != len(inputs) or any(len(output) != 20 for output in expected):
            raise ValueError('Incomplete original oracle output')
        cases.append(dict(id=case_id, target_formulas=['Amazing Surf 2'],
                          scene=path.resolve().relative_to(ROOT).as_posix(), sha256=sha(path)))
        for xyz, output in zip(inputs, expected):
            rows.append(dict(case=case_id, name='Amazing Surf 2', option_count=7,
                             options=options, input=xyz,
                             output=[format(x, '.17g') for x in output]))
    report = dict(scope=__doc__, cpp_parameter_probe_sha256=sha(args.cpp),
                  oracle_sha256=sha(args.oracle), asset_sha256=sha(asset),
                  original_code_sha256=sha(code), source_scene_sha256=sha(args.base),
                  generator_sha256=sha(Path(__file__)), input_sha256=__import__('hashlib').sha256(stdin.encode()).hexdigest(),
                  cases=cases, parameter_checks=parameter_checks, rows=rows)
    write_json(args.output / 'golden.json', report)
    write_json(args.output / 'manifest.json', dict(scope=__doc__, cases=cases))
    header = '// Original x86 outputs; generated by capture_surf2_selector_regressions.py.\n'
    header += 'struct FormulaRegression { const char* name; int option_count; double options[16], input[4], output[20]; const char* case_id; };\n'
    header += 'static const FormulaRegression formulaRegressions[] = {\n'
    for row in rows:
        arrays = ', '.join('{' + ', '.join(map(literal, row[key])) + '}' for key in ('options', 'input', 'output'))
        header += '    {"Amazing Surf 2", 7, ' + arrays + ', ' + json.dumps(row['case']) + '},\n'
    args.header.write_text(header + '};\n', encoding='utf-8')
    print(len(rows), 'independent original-code rows;', len(parameter_checks), 'verified masks')


if __name__ == '__main__':
    main()
