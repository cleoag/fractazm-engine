"""Capture the Pascal INTEGER/2INTEGER option conversion, including narrowing.

Compiles only in the authorized external Pascal work tree. The assignment is
extracted from immutable CustomFormulas.pas; no C++ arithmetic is the oracle.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[2]
WORK = Path('C:/work/_c/mb3d_pascal_work/mb3d_work/integer_option_oracle')
FPC = Path('C:/FPC/3.2.2/bin/i386-Win32/fpc.exe')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--fixture', type=Path, required=True)
    args = ap.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    WORK.mkdir(parents=True, exist_ok=True)
    source = ROOT / 'mb3d/CustomFormulas.pas'
    assignment = 'PInteger(p)^ := Round(dOptionValues[i]);'
    assert source.read_text().count(assignment) == 3
    power_expr = 'Max(2, Min(8, Round(dOptionValues[i - 2])))'
    assert power_expr in source.read_text()
    pas = WORK / 'integer_option_oracle.pas'
    pas.write_text('''program integer_option_oracle;
{$mode delphi}{$R-}{$Q-}
uses SysUtils, Math;
var bits: QWord; line: string; mode, i, power: Integer;
    dOptionValues: array[0..2] of Double;
    p: Pointer; value: Integer;
begin
  SetExceptionMask([exInvalidOp, exDenormalized, exZeroDivide,
                    exOverflow, exUnderflow, exPrecision]);
  i := 0; p := @value;
  while not Eof do begin
    ReadLn(line);
    mode := StrToInt(Copy(line, 1, 1));
    bits := StrToQWord('$' + Copy(line, 3, 16));
    Move(bits, dOptionValues[0], 8);
    SetRoundMode(TFPURoundingMode(mode));
    ''' + assignment + '''
    i := 2;
    power := ''' + power_expr + ''';
    i := 0;
    WriteLn(mode, ' ', IntToHex(bits, 16), ' ', value, ' ', power);
  end;
end.
''')
    command = [str(FPC), '-Mdelphi', '-CfSSE2', '-O2', '-al', str(pas)]
    build = subprocess.run(command, cwd=WORK, capture_output=True, timeout=60)
    (args.output/'build.log').write_bytes(build.stdout + build.stderr)
    build.check_returncode()
    values = [0., -0., math.inf, -math.inf, math.nan]
    for base in [.5, 1.5, 2.5, 3.5, 7.5, 8.5, 2147483647.5,
                 2147483648., 4294967295., 4294967296., 2.**52, 2.**63]:
        for sign in [1., -1.]:
            value = sign * base
            values += [math.nextafter(value, -math.inf), value,
                       math.nextafter(value, math.inf)]
    bits = list(dict.fromkeys(struct.unpack('<Q', struct.pack('<d', v))[0] for v in values))
    inputs = ''.join(f'{mode} {v:016X}\n' for mode in range(4) for v in bits)
    exe = pas.with_suffix('.exe')
    run = subprocess.run([str(exe)], input=inputs.encode(), capture_output=True, timeout=15)
    (args.output/'inputs.txt').write_text(inputs)
    (args.output/'output.txt').write_bytes(run.stdout)
    run.check_returncode()
    rows = [line.split() for line in run.stdout.decode().splitlines()]
    assert len(rows) == 4 * len(bits)
    text = ['// Generated by capture_integer_option_rounding.py from the original Pascal assignment.',
            '// Modes: FPC rmNearest=0, rmDown=1, rmUp=2, rmTruncate=3.',
            'struct IntegerOptionFixture { int mode; uint64_t bits; int32_t expected; int expected_power; };',
            'static const IntegerOptionFixture kIntegerOptionFixtures[] = {']
    text += [f'    {{{mode}, UINT64_C(0x{v}), {result}, {power}}},' for mode, v, result, power in rows]
    text += ['};', '']
    args.fixture.write_text('\n'.join(text))
    for artifact in [pas, exe, pas.with_suffix('.s')]:
        (args.output/artifact.name).write_bytes(artifact.read_bytes())
    identity = {'scope': 'Original Pascal Round(Double): INTEGER/2INTEGER narrowing and FOLDING power clamp',
                'rows': len(rows), 'command': command,
                'sha256': {str(p): sha(p) for p in [source, pas, exe, FPC,
                           FPC.with_name('ppc386.exe'), Path(__file__), args.fixture]}}
    (args.output/'identity.json').write_text(json.dumps(identity, indent=2))
    print(json.dumps({'rows': len(rows), 'fixture': str(args.fixture)}))


if __name__ == '__main__':
    main()
