"""Capture the actual FPC LongBool predicate used twice by original CalcSR.

This qualifies the current FPC i386 reference profile, not Delphi. The original
expression is compiled unchanged; expected results are never computed in Python.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

from external_validation import ROOT, write_json

SOURCE = '''program transmission_predicate;
{$mode delphi}
var initialInside,currentInside:LongBool; i,j,outside,transmitting,attenuate:Integer;
begin
 for i:=0 to 1 do for j:=0 to 1 do begin
  initialInside:=i<>0; currentInside:=j<>0;
  if not initialInside xor currentInside then outside:=1 else outside:=0;
  if initialInside xor currentInside then attenuate:=1 else attenuate:=0;
  for transmitting:=0 to 1 do
   Writeln(i,' ',j,' ',transmitting,' ',LongInt(initialInside),' ',LongInt(currentInside),
    ' ',outside,' ',attenuate,' ',Ord((not LongBool(transmitting<>0)) or
      (not initialInside xor currentInside))<>0);
 end;
end.
'''


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--fpc',type=Path,default=Path('C:/FPC/3.2.2/bin/i386-Win32/fpc.exe'))
    ap.add_argument('--work',type=Path,default=Path('C:/work/_c/mb3d_pascal_work/mb3d_work/audit_openair'))
    ap.add_argument('--output',type=Path,required=True)
    ap.add_argument('--header',type=Path,required=True)
    a=ap.parse_args();a.work.mkdir(parents=True,exist_ok=True);a.output.mkdir(parents=True,exist_ok=True)
    source=a.work/'transmission_predicate.pas';source.write_text(SOURCE,encoding='ascii')
    command=[str(a.fpc),'-Mdelphi','-O2','-CfSSE2',str(source)]
    build=subprocess.run(command,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,check=True)
    exe=source.with_suffix('.exe');run=subprocess.run([str(exe)],capture_output=True,check=True)
    (a.output/'source.pas').write_text(SOURCE,encoding='ascii')
    (a.output/'build.log').write_bytes(build.stdout);(a.output/'output.txt').write_bytes(run.stdout)
    rows=[]
    for line in run.stdout.decode('ascii').splitlines():
        values=line.split();rows.append([*map(int,values[:7]),int(values[7]=='TRUE')])
    if len(rows)!=8:raise ValueError('Incomplete predicate output')
    report=dict(scope=__doc__,compiler_sha256=sha(a.fpc),oracle_sha256=sha(exe),source_sha256=sha(source),
        original_source_sha256=sha(ROOT/'mb3d/CalcSR.pas'),command=command,rows=rows)
    write_json(a.output/'summary.json',report)
    header='// Generated by capture_transmission_predicate.py from unchanged Pascal expressions.\n'
    header+='struct TransmissionPredicateFixture { int initial, current, transmitting, raw_initial, raw_current, outside, attenuate, multiply_specular; };\n'
    header+='static const TransmissionPredicateFixture kTransmissionPredicates[] = {\n'
    header+=''.join('    {'+', '.join(map(str,r))+'},\n' for r in rows)+'};\n'
    a.header.write_text(header,encoding='ascii');print(json.dumps(rows))


if __name__=='__main__':main()
