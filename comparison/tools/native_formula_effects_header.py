#!/usr/bin/env python3
"""Write the compiler-derived formula state masks as a host header.

The input is effects.json from native_formula_effects.py. Each entry becomes
read and write masks over NativeFormulaState words (bit n = word n, the
pixel_state_contract.h StateMask layout). Surviving AIR loads over-approximate
reads before write; stores are possible writes; imprecise lanes count as both.
No must-write is claimed. Contained lanes are reads whose values reach only
the same lane's own write (an in-place rescale).

External entries bind the exact slot metadata the analysis specialized.
Internal entries were analyzed with runtime slot metadata, so they match any
metadata for their ID.

AnalyzePrimaryPixelState uses these masks for slots the hand audit does not
know; an independent contract selects pixel primary ownership in production.
Generation refuses effects whose formula bodies, wrapper, math (including the
translate-add helper) or internal formulas differ from the checkout. A manifest
beside the header lists those sources with their hashes and the header records
the manifest digest. CMake
configuration and test_native_formula_effects_header.py fail on later source
changes until the analysis and this header are regenerated.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import native_formula_effects as fx

ROOT = fx.ROOT
OUTPUT = Path("src/render/native_metal/generated/formula_state_effects.h")
MANIFEST_SUFFIX = ".sources.tsv"
WRAPPER = fx.NATIVE / "formula_wrapper.metal.h"
MATH = fx.NATIVE / "formula_math.metal.h"
TRANSLATE_ADD = fx.NATIVE / "translate_add.metal.h"
RESULT_CONTRACT = fx.NATIVE / "generated/formula_result_contracts.metal.h"
NAMESPACES = {"internal": 0, "external": 1}


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def mask(names):
    value = 0
    for name in names:
        value |= 1 << fx.LANES.index(name)
    return value


def sources(effects):
    """Recorded identities of analyzed bodies, wrapper and shared math."""
    contract = effects.get("result_contract_sha256")
    if not isinstance(contract, str) or len(contract) != 64 or any(c not in "0123456789abcdef" for c in contract):
        raise ValueError("Missing analyzed result contract identity; regenerate effects")
    math = effects.get("math_sha256")
    if not isinstance(math, str) or len(math) != 64 or any(c not in "0123456789abcdef" for c in math):
        raise ValueError("Missing analyzed math identity; regenerate effects")
    translate_add = effects.get("translate_add_sha256")
    if not isinstance(translate_add, str) or len(translate_add) != 64 or any(c not in "0123456789abcdef" for c in translate_add):
        raise ValueError("Missing analyzed translate add helper identity; regenerate effects")
    pairs = {str(WRAPPER): effects["wrapper_sha256"], str(MATH): math,
             str(TRANSLATE_ADD): translate_add, str(RESULT_CONTRACT): contract}
    for entry in effects["formulas"] + effects["internal_formulas"]:
        pairs[entry["generated"]] = entry["generated_sha256"]
    return sorted(pairs.items())


def manifest(pairs):
    return "".join(f"{path}\t{digest}\n" for path, digest in pairs)


def stale(root, pairs):
    return [path for path, digest in pairs if not (root / path).is_file() or sha256(root / path) != digest]


def entries(effects):
    rows = []
    for entry in effects["formulas"] + effects["internal_formulas"]:
        result = entry["effects"]
        if result.get("status") != "ANALYZED" or result.get("opaque"):
            continue
        imprecise = set(result.get("imprecise", ()))
        internal = entry.get("namespace") == "internal"
        rows.append({
            "namespace": NAMESPACES["internal" if internal else "external"], "id": entry["id"], "exact": not internal,
            "de_option": 0 if internal else entry["de_option"], "param_count": 0 if internal else entry["param_count"],
            "traits": 0 if internal else entry["traits"], "wrapper_flags": 0 if internal else entry["wrapper_flags"],
            "reads": mask(set(result["consumed"]) | imprecise), "writes": mask(set(result["written"]) | imprecise),
            "contained": mask(set(result.get("self_only", ())) - imprecise)})
    rows.sort(key=lambda r: (r["namespace"], r["id"]))
    keys = [(r["namespace"], r["id"]) for r in rows]
    if len(keys) != len(set(keys)):
        raise ValueError("Duplicate formula identity in effects")
    return rows


def render(rows, effects_sha256, digest):
    lines = [
        "#pragma once",
        "// Generated by comparison/tools/native_formula_effects_header.py; do not edit.",
        "// Compiler-derived NativeFormulaState masks (bit n = state word n). Reads",
        "// over-approximate reads before write; writes are possible writes; a",
        "// contained read reaches only its own lane's write. They admit primary",
        "// pixel ownership; configuration checks the source manifest.",
        "#include <cstdint>",
        "namespace mb3d_native::generated_effects {",
        "struct Entry {",
        "    std::uint32_t namespace_id,id;",
        "    bool exact; // false: analyzed with runtime slot metadata (internal bodies)",
        "    std::int32_t de_option;",
        "    std::uint32_t param_count,traits,wrapper_flags;",
        "    std::uint64_t reads,writes,contained;",
        "};",
        f'inline constexpr char kEffectsSha256[]="{effects_sha256}";',
        f'inline constexpr char kSourcesSha256[]="{digest}";',
        "inline constexpr Entry kEntries[]={",
    ]
    for r in rows:
        lines.append(f"    {{{r['namespace']},{r['id']},{'true' if r['exact'] else 'false'},{r['de_option']},"
                     f"{r['param_count']},{r['traits']},{r['wrapper_flags']},"
                     f"0x{r['reads']:x}ull,0x{r['writes']:x}ull,0x{r['contained']:x}ull}},")
    lines += ["};", "} // namespace mb3d_native::generated_effects", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--effects", type=Path, required=True, help="effects.json from native_formula_effects.py")
    parser.add_argument("--output", type=Path, default=ROOT / OUTPUT)
    args = parser.parse_args()
    effects = json.loads(args.effects.read_text())
    if effects.get("schema") != fx.SCHEMA or effects.get("lanes") != list(fx.LANES):
        raise SystemExit("Unexpected effects schema or lane layout")
    pairs = sources(effects)
    changed = stale(ROOT, pairs)
    if changed:
        raise SystemExit(f"Effects are stale for {len(changed)} sources, first: {changed[0]}")
    rows = entries(effects)
    text = manifest(pairs)
    args.output.with_name(args.output.name.removesuffix(".h") + MANIFEST_SUFFIX).write_text(text)
    args.output.write_text(render(rows, sha256(args.effects), hashlib.sha256(text.encode()).hexdigest()))
    print(f"{args.output}: {len(rows)} entries, {len(pairs)} sources")


if __name__ == "__main__":
    main()
