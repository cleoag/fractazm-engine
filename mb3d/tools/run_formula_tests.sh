#!/bin/bash
# Run headless render tests for all built-in MB3D formulas.
# Usage: bash tools/run_formula_tests.sh
#
# Prerequisites:
#   - Mandelbulb3D.exe built with FPC (headless mode support)
#   - Python 3 available for gen_formula_tests.py

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
EXE="$PROJECT_DIR/Mandelbulb3D.exe"
GEN_SCRIPT="$SCRIPT_DIR/gen_formula_tests.py"
SYNTH_DIR="$PROJECT_DIR/M3Parameter_test"
OUTPUT_DIR="$PROJECT_DIR/formula_test_output"
REPORT="$OUTPUT_DIR/formula_test_report.txt"

RENDER_WIDTH=480
RENDER_HEIGHT=360
TIMEOUT=120  # seconds

# Colors for terminal output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# ── Check prerequisites ──────────────────────────────────────────────
if [[ ! -f "$EXE" ]]; then
    echo -e "${RED}ERROR: $EXE not found. Build with FPC first.${NC}"
    exit 1
fi

if ! command -v python3 &>/dev/null; then
    echo -e "${RED}ERROR: python3 not found.${NC}"
    exit 1
fi

# ── Generate synthetic test scenes ───────────────────────────────────
echo "=== Generating synthetic formula test scenes ==="
python3 "$GEN_SCRIPT"
echo

# ── Prepare output directory ─────────────────────────────────────────
mkdir -p "$OUTPUT_DIR"
> "$REPORT"  # truncate report

# ── Define test scenes ───────────────────────────────────────────────
# Synthetic scenes (generated by gen_formula_tests.py)
SYNTH_SCENES=(
    "formula_0_IntPow2.m3p"
    "formula_0_IntPow3.m3p"
    "formula_0_IntPow4.m3p"
    "formula_0_IntPow5.m3p"
    "formula_0_IntPow6.m3p"
    "formula_0_IntPow7.m3p"
    "formula_0_IntPow8.m3p"
    "formula_1_RealPower.m3p"
    "formula_2_Quaternion.m3p"
    "formula_3_Tricorn.m3p"
    "formula_4_AmazingBox.m3p"
    "formula_5_Bulbox.m3p"
    "formula_6_FoldIntPow.m3p"
    "formula_9_AexionC.m3p"
)

# Existing scenes that use built-in formulas (from M3Parameter/)
EXISTING_SCENES=(
    "JuliaSetSample.m3p"           # IntPow3 + ext _JuliaSets
    "QuatP4hybridJulia.m3p"        # IntPow4 + Quaternion hybrid
    "spineJulia.m3p"               # IntPow8 (reference)
    "BulboxCut.m3p"                # Bulbox (iFnr=5)
    "Theli-At - Black Mandelbulb.m3p"  # Tricorn (iFnr=3)
    "ABoxScale2Start.m3p"          # AmazingBox (iFnr=4)
    "Fractales75 - Kiosk.m3p"      # FoldingIntPow (iFnr=6)
)

# ── Run tests ────────────────────────────────────────────────────────
PASS=0
FAIL=0
SKIP=0
TOTAL=0

run_test() {
    local scene_file="$1"
    local scene_dir="$2"
    local scene_name
    scene_name="$(basename "$scene_file" .m3p)"

    local input_path="$scene_dir/$scene_file"
    local output_path="$OUTPUT_DIR/${scene_name}.png"

    TOTAL=$((TOTAL + 1))

    if [[ ! -f "$input_path" ]]; then
        echo -e "  ${YELLOW}SKIP${NC}  $scene_file  (file not found)"
        echo "SKIP  $scene_file  (file not found)" >> "$REPORT"
        SKIP=$((SKIP + 1))
        return
    fi

    local start_time
    start_time=$(date +%s)

    # Run headless render with timeout
    local exit_code=0
    timeout "$TIMEOUT" "$EXE" \
        --render "$input_path" \
        --output "$output_path" \
        --width "$RENDER_WIDTH" \
        --height "$RENDER_HEIGHT" \
        --format png \
        2>&1 || exit_code=$?

    local end_time
    end_time=$(date +%s)
    local elapsed=$((end_time - start_time))

    if [[ $exit_code -eq 124 ]]; then
        echo -e "  ${RED}FAIL${NC}  $scene_file  (TIMEOUT after ${TIMEOUT}s)"
        echo "FAIL  $scene_file  TIMEOUT after ${TIMEOUT}s" >> "$REPORT"
        FAIL=$((FAIL + 1))
    elif [[ $exit_code -ne 0 ]]; then
        echo -e "  ${RED}FAIL${NC}  $scene_file  (exit code $exit_code, ${elapsed}s)"
        echo "FAIL  $scene_file  exit_code=$exit_code  ${elapsed}s" >> "$REPORT"
        FAIL=$((FAIL + 1))
    elif [[ ! -f "$output_path" ]]; then
        echo -e "  ${RED}FAIL${NC}  $scene_file  (no output file, ${elapsed}s)"
        echo "FAIL  $scene_file  no_output  ${elapsed}s" >> "$REPORT"
        FAIL=$((FAIL + 1))
    else
        local fsize
        fsize=$(stat -c%s "$output_path" 2>/dev/null || stat -f%z "$output_path" 2>/dev/null || echo 0)
        if [[ "$fsize" -lt 1000 ]]; then
            echo -e "  ${RED}FAIL${NC}  $scene_file  (output too small: ${fsize} bytes, ${elapsed}s)"
            echo "FAIL  $scene_file  small_output=${fsize}bytes  ${elapsed}s" >> "$REPORT"
            FAIL=$((FAIL + 1))
        else
            echo -e "  ${GREEN}PASS${NC}  $scene_file  (${fsize} bytes, ${elapsed}s)"
            echo "PASS  $scene_file  ${fsize}bytes  ${elapsed}s" >> "$REPORT"
            PASS=$((PASS + 1))
        fi
    fi
}

echo "=== Running synthetic formula tests (${#SYNTH_SCENES[@]} scenes) ==="
for scene in "${SYNTH_SCENES[@]}"; do
    run_test "$scene" "$SYNTH_DIR"
done

echo
echo "=== Running existing scene tests (${#EXISTING_SCENES[@]} scenes) ==="
for scene in "${EXISTING_SCENES[@]}"; do
    run_test "$scene" "$PROJECT_DIR/M3Parameter"
done

# ── Summary ──────────────────────────────────────────────────────────
echo
echo "=============================================="
echo "  Formula Test Results"
echo "=============================================="
echo -e "  ${GREEN}PASS${NC}: $PASS"
echo -e "  ${RED}FAIL${NC}: $FAIL"
echo -e "  ${YELLOW}SKIP${NC}: $SKIP"
echo "  TOTAL: $TOTAL"
echo "=============================================="
echo
echo "Report: $REPORT"
echo "Output: $OUTPUT_DIR/"

# Write summary to report
echo >> "$REPORT"
echo "SUMMARY: PASS=$PASS FAIL=$FAIL SKIP=$SKIP TOTAL=$TOTAL" >> "$REPORT"

# Exit with failure if any tests failed
if [[ $FAIL -gt 0 ]]; then
    exit 1
fi
